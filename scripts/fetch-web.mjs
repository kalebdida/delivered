// pnpm fetch:web
// Downloads the World English Bible (public domain) USFM from ebible.org and writes ONLY the
// verses listed in scripture-refs.mjs into packages/core/src/scripture/scripture.en.ts.
import { writeFileSync } from 'node:fs';
import { REFS, WEB_ZIP, tsString } from './scripture-refs.mjs';
import { parseUsfm, unzipFile } from './usfm.mjs';

const res = await fetch(WEB_ZIP);
if (!res.ok) throw new Error(`ebible.org responded ${res.status}`);
const zip = Buffer.from(await res.arrayBuffer());
const lines = [];
for (const [book, code, , chapters] of REFS) {
  const verses = parseUsfm(unzipFile(zip, (n) => n.includes(`${code}eng-web.usfm`)));
  for (const [chapter, list] of Object.entries(chapters)) {
    for (const v of list) {
      const text = verses.get(`${chapter}:${v}`);
      if (!text) throw new Error(`Missing ${book} ${chapter}:${v}`);
      lines.push(
        `  { ref: ${tsString(`${book} ${chapter}:${v}`)}, lang: 'en', translation: 'WEB', verified: true, source: ${tsString(WEB_ZIP)},\n    text: ${tsString(text)} },`,
      );
    }
  }
}
const file = `// GENERATED by scripts/fetch-web.mjs from ebible.org. Do not edit by hand.
// World English Bible (WEB), public domain. Verify with \`pnpm verify:scripture\`.
export const scriptureEn = [
${lines.join('\n')}
];
`;
writeFileSync(new URL('../packages/core/src/scripture/scripture.en.ts', import.meta.url), file);
console.log(`Wrote ${lines.length} WEB verses.`);
