// pnpm fetch:amharic
// Extracts ONLY the verses listed in scripture-refs.mjs from a public dataset of the 1962
// Revised Amharic Bible and writes packages/core/src/scripture/scripture.am.ts.
//
// The text is copyright (c) 1962, 2003 United Bible Societies / Bible Society of Ethiopia.
// DELIVERED quotes a handful of verses for non-commercial use and never ships the whole Bible.
//
// Every verse is cross-checked against a second, independently scraped dataset. Outcomes:
//   match      both sources agree (after whitespace normalization)
//   completed  the primary source truncated the verse (it keeps only the first poetic line);
//              the full text is taken from the secondary source, which starts identically
//   merged     the Amharic translation merges this verse with a neighbour; the merged text is kept
//   single     only one source has it; kept, marked unverified
//   mismatch   the sources disagree; primary kept, marked unverified
import { writeFileSync } from 'node:fs';
import { AM_PRIMARY, AM_SECONDARY, REFS, normalize, rawUrl, tsString } from './scripture-refs.mjs';

const get = async (src, file) => {
  const res = await fetch(rawUrl(src, file));
  if (!res.ok) throw new Error(`${src.repo}/${file}: ${res.status}`);
  return res.json();
};

const lines = [];
const report = [];
for (const [book, , num, chapters] of REFS) {
  const [a, b] = await Promise.all([get(AM_PRIMARY, AM_PRIMARY.files[num]), get(AM_SECONDARY, AM_SECONDARY.files[num])]);
  for (const [chapter, list] of Object.entries(chapters)) {
    const ach = a.chapters.find((c) => c.chapter === Number(chapter));
    const bch = b.chapters.find((c) => c.chapter === String(chapter));
    const second = (bch?.verses ?? []).map(normalize);
    for (const v of list) {
      const ref = `${book} ${chapter}:${v}`;
      const entry = ach?.verses.find((x) => x.verse === v);
      const primary = entry?.text?.am ? normalize(entry.text.am) : '';
      const merged = entry?.mergedWith?.am;
      let text = primary;
      let status = 'mismatch';
      const sameIndex = second[v - 1] ?? '';
      if (!primary && sameIndex.length > 1) {
        text = sameIndex;
        status = 'single';
      } else if (second.includes(primary)) {
        status = merged ? 'merged' : 'match';
      } else if (primary && sameIndex.startsWith(primary) && sameIndex.length > primary.length) {
        text = sameIndex;
        status = 'completed';
      } else if (primary && second.some((s) => s.replace(/\s/g, '') === primary.replace(/\s/g, ''))) {
        status = merged ? 'merged' : 'match'; // differs only in spacing around punctuation
      } else if (merged) {
        status = 'merged-unconfirmed';
      }
      if (!text) throw new Error(`Missing ${ref}`);
      const verified = status === 'match' || status === 'merged';
      const note = merged ? `In the Amharic text, verses ${merged[0]}-${merged[merged.length - 1]} are one sentence.` : '';
      report.push(`${ref}: ${status}`);
      lines.push(
        `  { ref: ${tsString(ref)}, lang: 'am', translation: 'AM1962', verified: ${verified}, crossCheck: ${tsString(status)}, source: ${tsString(`github.com/${(status === 'completed' || status === 'single' ? AM_SECONDARY : AM_PRIMARY).repo}`)},${note ? ` note: ${tsString(note)},` : ''}\n    text: ${tsString(text)} },`,
      );
    }
  }
}
const file = `// GENERATED by scripts/fetch-amharic.mjs. Do not edit by hand.
// Revised Amharic Bible (1962), (c) United Bible Societies / Bible Society of Ethiopia.
// Used for non-commercial purposes. Only the verses DELIVERED quotes are included.
// Primary:   github.com/${AM_PRIMARY.repo} @ ${AM_PRIMARY.commit}
// Secondary: github.com/${AM_SECONDARY.repo} @ ${AM_SECONDARY.commit}
export const scriptureAm = [
${lines.join('\n')}
];
`;
writeFileSync(new URL('../packages/core/src/scripture/scripture.am.ts', import.meta.url), file);
console.log(report.join('\n'));
console.log(`\nWrote ${lines.length} Amharic verses.`);
